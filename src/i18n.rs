use serde::{Deserialize, Serialize};
use sys_locale::get_locale;

#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
pub enum Language {
    #[default]
    System,
    Zh,
    En,
}

impl Language {
    pub fn display_name(&self) -> &'static str {
        match self {
            Language::System => "🌐 Auto (System)",
            Language::Zh => "🇨🇳 中文",
            Language::En => "🇺🇸 English",
        }
    }

    pub fn all() -> Vec<Self> {
        vec![Language::System, Language::Zh, Language::En]
    }
}

pub fn detect_system_language() -> Language {
    if let Some(locale) = get_locale() {
        let l = locale.to_lowercase();
        if l.starts_with("zh") || l.contains("cn") || l.contains("tw") || l.contains("hk") {
            return Language::Zh;
        }
    }
    if let Ok(lang_env) = std::env::var("LANG") {
        let l = lang_env.to_lowercase();
        if l.contains("zh") || l.contains("cn") {
            return Language::Zh;
        }
    }
    Language::En
}

pub fn resolve_language(lang: &Language) -> Language {
    match lang {
        Language::System => detect_system_language(),
        Language::Zh => Language::Zh,
        Language::En => Language::En,
    }
}

